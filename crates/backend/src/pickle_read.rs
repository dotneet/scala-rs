struct Reader<'a> {
    bytes: &'a [u8],
    pos: usize,
    entry: usize,
    tag: u8,
}

impl<'a> Reader<'a> {
    fn new(bytes: &'a [u8]) -> Self {
        Reader {
            bytes,
            pos: 0,
            entry: usize::MAX,
            tag: 0,
        }
    }

    fn err<T>(&self, message: impl Into<String>) -> Result<T> {
        Err(ReadError {
            entry: self.entry,
            tag: self.tag,
            offset: self.pos,
            message: message.into(),
        })
    }

    fn byte(&mut self) -> Result<u8> {
        if self.pos >= self.bytes.len() {
            return self.err("unexpected end of pickle");
        }
        let b = self.bytes[self.pos];
        self.pos += 1;
        Ok(b)
    }

    fn long_nat(&mut self) -> Result<u64> {
        let mut x: u64 = 0;
        for _ in 0..10 {
            let b = self.byte()? as u64;
            x = (x << 7) | (b & 0x7f);
            if b & 0x80 == 0 {
                return Ok(x);
            }
        }
        self.err("Nat longer than 10 bytes")
    }

    fn nat(&mut self) -> Result<u32> {
        let v = self.long_nat()?;
        if v > u32::MAX as u64 {
            return self.err(format!("Nat {v} does not fit in u32"));
        }
        Ok(v as u32)
    }

    /// nsc `readLong(len)`: signed big-endian over exactly `len` bytes.
    fn long(&mut self, len: usize) -> Result<i64> {
        if len > 8 {
            return self.err(format!("constant of {len} bytes"));
        }
        let mut x: i64 = 0;
        for _ in 0..len {
            x = (x << 8) | (self.byte()? as i64);
        }
        let leading = 64 - (len << 3);
        Ok((x << leading) >> leading)
    }
}

/// Read a complete pickle. Fails on any unknown tag or malformed body.
pub fn read_pickle(bytes: &[u8]) -> Result<Pickle> {
    let mut r = Reader::new(bytes);
    let major = r.nat()?;
    let minor = r.nat()?;
    if major != crate::pickle::MAJOR {
        return r.err(format!("unsupported pickle major version {major}"));
    }
    let nentries = r.nat()? as usize;

    // Pass 1: entry offsets and tags (needed for isSymbolRef / isNameEntry).
    let mut offsets = Vec::with_capacity(nentries);
    let mut entry_tags = Vec::with_capacity(nentries);
    let mut ends = Vec::with_capacity(nentries);
    for i in 0..nentries {
        r.entry = i;
        r.tag = 0;
        let tag = r.byte()?;
        r.tag = tag;
        let len = r.nat()? as usize;
        let start = r.pos;
        let end = match start.checked_add(len) {
            Some(e) if e <= r.bytes.len() => e,
            _ => return r.err(format!("entry length {len} overruns the pickle")),
        };
        offsets.push(start);
        entry_tags.push(tag);
        ends.push(end);
        r.pos = end;
    }

    // Pass 2: bodies.
    let mut entries = Vec::with_capacity(nentries);
    for i in 0..nentries {
        r.entry = i;
        r.tag = entry_tags[i];
        r.pos = offsets[i];
        let end = ends[i];
        let e = read_entry(&mut r, end, &entry_tags, nentries)?;
        if r.pos != end {
            return r.err(format!(
                "entry body not fully consumed ({} of {} bytes)",
                r.pos - offsets[i],
                end - offsets[i]
            ));
        }
        entries.push(e);
    }

    Ok(Pickle {
        major,
        minor,
        entries,
        entry_tags,
    })
}

fn check_ref(r: &Reader, idx: Idx, nentries: usize) -> Result<()> {
    if idx as usize >= nentries {
        return r.err(format!(
            "reference #{idx} out of range ({nentries} entries)"
        ));
    }
    Ok(())
}

fn read_ref(r: &mut Reader, nentries: usize) -> Result<Idx> {
    let i = r.nat()?;
    check_ref(r, i, nentries)?;
    Ok(i)
}

fn read_refs_until(r: &mut Reader, end: usize, nentries: usize) -> Result<Vec<Idx>> {
    let mut out = Vec::new();
    while r.pos < end {
        out.push(read_ref(r, nentries)?);
    }
    Ok(out)
}

fn is_sym_ref(all_tags: &[u8], i: Idx) -> bool {
    all_tags
        .get(i as usize)
        .is_some_and(|&t| (tags::FIRST_SYM_TAG..=tags::LAST_EXT_SYM_TAG).contains(&t))
}

fn is_name_entry(all_tags: &[u8], i: Idx) -> bool {
    matches!(
        all_tags.get(i as usize),
        Some(&tags::TERMname) | Some(&tags::TYPEname)
    )
}

fn read_sym_info(r: &mut Reader, all_tags: &[u8], nentries: usize) -> Result<SymInfo> {
    let name = read_ref(r, nentries)?;
    let owner = read_ref(r, nentries)?;
    let flags = r.long_nat()?;
    let first = read_ref(r, nentries)?;
    let (private_within, info) = if is_sym_ref(all_tags, first) {
        (Some(first), read_ref(r, nentries)?)
    } else {
        (None, first)
    };
    Ok(SymInfo {
        name,
        owner,
        flags,
        private_within,
        info,
    })
}

fn read_annot_info(
    r: &mut Reader,
    end: usize,
    all_tags: &[u8],
    nentries: usize,
) -> Result<AnnotInfo> {
    let tpe = read_ref(r, nentries)?;
    let mut args = Vec::new();
    let mut assocs = Vec::new();
    while r.pos < end {
        let a = read_ref(r, nentries)?;
        if is_name_entry(all_tags, a) {
            let v = read_ref(r, nentries)?;
            assocs.push((a, v));
        } else {
            args.push(a);
        }
    }
    Ok(AnnotInfo { tpe, args, assocs })
}

fn read_name(r: &mut Reader, end: usize) -> Result<String> {
    let raw = &r.bytes[r.pos..end];
    r.pos = end;
    // nsc writes names as UTF-8 (surrogates encoded individually, i.e. CESU-8);
    // the lossy path only matters for names outside the BMP, which the standard
    // library does not contain.
    Ok(String::from_utf8_lossy(raw).into_owned())
}

fn read_entry(r: &mut Reader, end: usize, all_tags: &[u8], n: usize) -> Result<Entry> {
    use tags as t;
    let tag = r.tag;
    let e = match tag {
        t::TERMname => Entry::TermName(read_name(r, end)?),
        t::TYPEname => Entry::TypeName(read_name(r, end)?),
        t::NONEsym => Entry::NoneSym,
        t::EXTref | t::EXTMODCLASSref => {
            let name = read_ref(r, n)?;
            let owner = if r.pos < end {
                Some(read_ref(r, n)?)
            } else {
                None
            };
            if tag == t::EXTref {
                Entry::ExtRef { name, owner }
            } else {
                Entry::ExtModClassRef { name, owner }
            }
        }
        t::TYPEsym => Entry::TypeSym(read_sym_info(r, all_tags, n)?),
        t::ALIASsym => Entry::AliasSym(read_sym_info(r, all_tags, n)?),
        t::CLASSsym => {
            let info = read_sym_info(r, all_tags, n)?;
            let this_type = if r.pos < end {
                Some(read_ref(r, n)?)
            } else {
                None
            };
            Entry::ClassSym { info, this_type }
        }
        t::MODULEsym | t::VALsym => {
            let info = read_sym_info(r, all_tags, n)?;
            let alias = if r.pos < end {
                Some(read_ref(r, n)?)
            } else {
                None
            };
            if tag == t::MODULEsym {
                Entry::ModuleSym { info, alias }
            } else {
                Entry::ValSym { info, alias }
            }
        }
        t::NOtpe => Entry::NoTpe,
        t::NOPREFIXtpe => Entry::NoPrefixTpe,
        t::THIStpe => Entry::ThisTpe(read_ref(r, n)?),
        t::SINGLEtpe => {
            let prefix = read_ref(r, n)?;
            let sym = read_ref(r, n)?;
            Entry::SingleTpe { prefix, sym }
        }
        t::SUPERtpe => {
            let this_tpe = read_ref(r, n)?;
            let super_tpe = read_ref(r, n)?;
            Entry::SuperTpe {
                this_tpe,
                super_tpe,
            }
        }
        t::CONSTANTtpe => Entry::ConstantTpe(read_ref(r, n)?),
        t::TYPEREFtpe => {
            let prefix = read_ref(r, n)?;
            let sym = read_ref(r, n)?;
            let args = read_refs_until(r, end, n)?;
            Entry::TypeRefTpe { prefix, sym, args }
        }
        t::TYPEBOUNDStpe => {
            let lo = read_ref(r, n)?;
            let hi = read_ref(r, n)?;
            Entry::TypeBoundsTpe { lo, hi }
        }
        t::REFINEDtpe => {
            let sym = read_ref(r, n)?;
            let parents = read_refs_until(r, end, n)?;
            Entry::RefinedTpe { sym, parents }
        }
        t::CLASSINFOtpe => {
            let sym = read_ref(r, n)?;
            let parents = read_refs_until(r, end, n)?;
            Entry::ClassInfoTpe { sym, parents }
        }
        t::METHODtpe | t::IMPLICITMETHODtpe => {
            let result = read_ref(r, n)?;
            let params = read_refs_until(r, end, n)?;
            if tag == t::METHODtpe {
                Entry::MethodTpe { result, params }
            } else {
                Entry::ImplicitMethodTpe { result, params }
            }
        }
        t::POLYtpe => {
            let result = read_ref(r, n)?;
            let tparams = read_refs_until(r, end, n)?;
            Entry::PolyTpe { result, tparams }
        }
        t::EXISTENTIALtpe => {
            let result = read_ref(r, n)?;
            let quantified = read_refs_until(r, end, n)?;
            Entry::ExistentialTpe { result, quantified }
        }
        t::ANNOTATEDtpe => {
            let tpe = read_ref(r, n)?;
            let annots = read_refs_until(r, end, n)?;
            Entry::AnnotatedTpe { tpe, annots }
        }
        t::DEBRUIJNINDEXtpe => {
            let level = r.nat()?;
            let index = r.nat()?;
            Entry::DeBruijnIndexTpe { level, index }
        }
        t::LITERALunit => Entry::Literal(Constant::Unit),
        t::LITERALboolean => Entry::Literal(Constant::Boolean(r.long(end - r.pos)? != 0)),
        t::LITERALbyte => Entry::Literal(Constant::Byte(r.long(end - r.pos)? as i8)),
        t::LITERALshort => Entry::Literal(Constant::Short(r.long(end - r.pos)? as i16)),
        t::LITERALchar => Entry::Literal(Constant::Char(r.long(end - r.pos)? as u32 & 0xffff)),
        t::LITERALint => Entry::Literal(Constant::Int(r.long(end - r.pos)? as i32)),
        t::LITERALlong => Entry::Literal(Constant::Long(r.long(end - r.pos)?)),
        t::LITERALfloat => {
            Entry::Literal(Constant::Float(f32::from_bits(r.long(end - r.pos)? as u32)))
        }
        t::LITERALdouble => Entry::Literal(Constant::Double(f64::from_bits(
            r.long(end - r.pos)? as u64
        ))),
        t::LITERALstring => Entry::Literal(Constant::Str(read_ref(r, n)?)),
        t::LITERALnull => Entry::Literal(Constant::Null),
        t::LITERALclass => Entry::Literal(Constant::Class(read_ref(r, n)?)),
        t::LITERALenum => Entry::Literal(Constant::Enum(read_ref(r, n)?)),
        t::LITERALsymbol => Entry::Literal(Constant::Symbol(read_ref(r, n)?)),
        t::SYMANNOT => {
            let sym = read_ref(r, n)?;
            let annot = read_annot_info(r, end, all_tags, n)?;
            Entry::SymAnnot { sym, annot }
        }
        t::ANNOTINFO => Entry::AnnotInfo(read_annot_info(r, end, all_tags, n)?),
        t::ANNOTARGARRAY => Entry::AnnotArgArray(read_refs_until(r, end, n)?),
        t::CHILDREN => {
            let sym = read_ref(r, n)?;
            let children = read_refs_until(r, end, n)?;
            Entry::Children { sym, children }
        }
        t::MODIFIERS => {
            let hi = r.nat()? as u64;
            let lo = r.nat()? as u64;
            let private_within = read_ref(r, n)?;
            Entry::Modifiers {
                flags: (hi << 32) | lo,
                private_within,
            }
        }
        t::TREE => read_tree_entry(r, end, n)?,
        _ => return r.err(format!("unknown pickle tag {tag}")),
    };
    Ok(e)
}

fn read_tree_entry(r: &mut Reader, end: usize, n: usize) -> Result<Entry> {
    use tags as t;
    let tt = r.byte()?;
    let tpe = if tt == t::EMPTYtree {
        None
    } else {
        Some(read_ref(r, n)?)
    };
    // `setSymModsName` order: symbol, modifiers, name.
    macro_rules! smn {
        () => {{
            let s = read_ref(r, n)?;
            let m = read_ref(r, n)?;
            let nm = read_ref(r, n)?;
            (s, m, nm)
        }};
    }
    let tree = match tt {
        t::EMPTYtree => Tree::Empty,
        t::PACKAGEtree => {
            let (sym, mods, name) = smn!();
            let pid = read_ref(r, n)?;
            let stats = read_refs_until(r, end, n)?;
            Tree::PackageDef {
                sym,
                mods,
                name,
                pid,
                stats,
            }
        }
        t::CLASStree => {
            let (sym, mods, name) = smn!();
            let template = read_ref(r, n)?;
            let tparams = read_refs_until(r, end, n)?;
            Tree::ClassDef {
                sym,
                mods,
                name,
                template,
                tparams,
            }
        }
        t::MODULEtree => {
            let (sym, mods, name) = smn!();
            let template = read_ref(r, n)?;
            Tree::ModuleDef {
                sym,
                mods,
                name,
                template,
            }
        }
        t::VALDEFtree => {
            let (sym, mods, name) = smn!();
            let tpt = read_ref(r, n)?;
            let rhs = read_ref(r, n)?;
            Tree::ValDef {
                sym,
                mods,
                name,
                tpt,
                rhs,
            }
        }
        t::DEFDEFtree => {
            let (sym, mods, name) = smn!();
            let ntp = r.nat()? as usize;
            let mut tparams = Vec::with_capacity(ntp);
            for _ in 0..ntp {
                tparams.push(read_ref(r, n)?);
            }
            let nss = r.nat()? as usize;
            let mut vparamss = Vec::with_capacity(nss);
            for _ in 0..nss {
                let np = r.nat()? as usize;
                let mut ps = Vec::with_capacity(np);
                for _ in 0..np {
                    ps.push(read_ref(r, n)?);
                }
                vparamss.push(ps);
            }
            let tpt = read_ref(r, n)?;
            let rhs = read_ref(r, n)?;
            Tree::DefDef {
                sym,
                mods,
                name,
                tparams,
                vparamss,
                tpt,
                rhs,
            }
        }
        t::TYPEDEFtree => {
            let (sym, mods, name) = smn!();
            let rhs = read_ref(r, n)?;
            let tparams = read_refs_until(r, end, n)?;
            Tree::TypeDef {
                sym,
                mods,
                name,
                rhs,
                tparams,
            }
        }
        t::LABELtree => {
            let sym = read_ref(r, n)?;
            let name = read_ref(r, n)?;
            let rhs = read_ref(r, n)?;
            let params = read_refs_until(r, end, n)?;
            Tree::LabelDef {
                sym,
                name,
                rhs,
                params,
            }
        }
        t::IMPORTtree => {
            let sym = read_ref(r, n)?;
            let expr = read_ref(r, n)?;
            let mut selectors = Vec::new();
            while r.pos < end {
                let from = read_ref(r, n)?;
                let to = read_ref(r, n)?;
                selectors.push(ImportSelector { from, to });
            }
            Tree::Import {
                sym,
                expr,
                selectors,
            }
        }
        t::DOCDEFtree => {
            let comment = read_ref(r, n)?;
            let definition = read_ref(r, n)?;
            Tree::DocDef {
                comment,
                definition,
            }
        }
        t::TEMPLATEtree => {
            let sym = read_ref(r, n)?;
            let np = r.nat()? as usize;
            let mut parents = Vec::with_capacity(np);
            for _ in 0..np {
                parents.push(read_ref(r, n)?);
            }
            let self_ = read_ref(r, n)?;
            let body = read_refs_until(r, end, n)?;
            Tree::Template {
                sym,
                parents,
                self_,
                body,
            }
        }
        t::BLOCKtree => {
            let expr = read_ref(r, n)?;
            let stats = read_refs_until(r, end, n)?;
            Tree::Block { expr, stats }
        }
        t::CASEtree => {
            let pat = read_ref(r, n)?;
            let guard = read_ref(r, n)?;
            let body = read_ref(r, n)?;
            Tree::CaseDef { pat, guard, body }
        }
        t::ALTERNATIVEtree => Tree::Alternative(read_refs_until(r, end, n)?),
        t::STARtree => Tree::Star(read_ref(r, n)?),
        t::BINDtree => {
            let sym = read_ref(r, n)?;
            let name = read_ref(r, n)?;
            let body = read_ref(r, n)?;
            Tree::Bind { sym, name, body }
        }
        t::UNAPPLYtree => {
            let fun = read_ref(r, n)?;
            let args = read_refs_until(r, end, n)?;
            Tree::UnApply { fun, args }
        }
        t::ARRAYVALUEtree => {
            let elemtpt = read_ref(r, n)?;
            let elems = read_refs_until(r, end, n)?;
            Tree::ArrayValue { elemtpt, elems }
        }
        t::FUNCTIONtree => {
            let sym = read_ref(r, n)?;
            let body = read_ref(r, n)?;
            let vparams = read_refs_until(r, end, n)?;
            Tree::Function { sym, body, vparams }
        }
        t::ASSIGNtree => {
            let lhs = read_ref(r, n)?;
            let rhs = read_ref(r, n)?;
            Tree::Assign { lhs, rhs }
        }
        t::IFtree => {
            let cond = read_ref(r, n)?;
            let thenp = read_ref(r, n)?;
            let elsep = read_ref(r, n)?;
            Tree::If { cond, thenp, elsep }
        }
        t::MATCHtree => {
            let selector = read_ref(r, n)?;
            let cases = read_refs_until(r, end, n)?;
            Tree::Match { selector, cases }
        }
        t::RETURNtree => {
            let sym = read_ref(r, n)?;
            let expr = read_ref(r, n)?;
            Tree::Return { sym, expr }
        }
        t::TREtree => {
            let block = read_ref(r, n)?;
            let finalizer = read_ref(r, n)?;
            let catches = read_refs_until(r, end, n)?;
            Tree::Try {
                block,
                finalizer,
                catches,
            }
        }
        t::THROWtree => Tree::Throw(read_ref(r, n)?),
        t::NEWtree => Tree::New(read_ref(r, n)?),
        t::TYPEDtree => {
            let expr = read_ref(r, n)?;
            let tpt = read_ref(r, n)?;
            Tree::Typed { expr, tpt }
        }
        t::TYPEAPPLYtree => {
            let fun = read_ref(r, n)?;
            let args = read_refs_until(r, end, n)?;
            Tree::TypeApply { fun, args }
        }
        t::APPLYtree => {
            let fun = read_ref(r, n)?;
            let args = read_refs_until(r, end, n)?;
            Tree::Apply { fun, args }
        }
        t::APPLYDYNAMICtree => {
            let sym = read_ref(r, n)?;
            let fun = read_ref(r, n)?;
            let args = read_refs_until(r, end, n)?;
            Tree::ApplyDynamic { sym, fun, args }
        }
        t::SUPERtree => {
            let sym = read_ref(r, n)?;
            let qual = read_ref(r, n)?;
            let mix = read_ref(r, n)?;
            Tree::Super { sym, qual, mix }
        }
        t::THIStree => {
            let sym = read_ref(r, n)?;
            let qual = read_ref(r, n)?;
            Tree::This { sym, qual }
        }
        t::SELECTtree => {
            let sym = read_ref(r, n)?;
            let qualifier = read_ref(r, n)?;
            let selector = read_ref(r, n)?;
            Tree::Select {
                sym,
                qualifier,
                selector,
            }
        }
        t::IDENTtree => {
            let sym = read_ref(r, n)?;
            let name = read_ref(r, n)?;
            Tree::Ident { sym, name }
        }
        t::LITERALtree => Tree::Literal(read_ref(r, n)?),
        t::TYPEtree => Tree::TypeTree,
        t::ANNOTATEDtree => {
            let annot = read_ref(r, n)?;
            let arg = read_ref(r, n)?;
            Tree::Annotated { annot, arg }
        }
        t::SINGLETONTYPEtree => Tree::SingletonTypeTree(read_ref(r, n)?),
        t::SELECTFROMTYPEtree => {
            let qualifier = read_ref(r, n)?;
            let selector = read_ref(r, n)?;
            Tree::SelectFromTypeTree {
                qualifier,
                selector,
            }
        }
        t::COMPOUNDTYPEtree => Tree::CompoundTypeTree(read_ref(r, n)?),
        t::APPLIEDTYPEtree => {
            let tpt = read_ref(r, n)?;
            let args = read_refs_until(r, end, n)?;
            Tree::AppliedTypeTree { tpt, args }
        }
        t::TYPEBOUNDStree => {
            let lo = read_ref(r, n)?;
            let hi = read_ref(r, n)?;
            Tree::TypeBoundsTree { lo, hi }
        }
        t::EXISTENTIALTYPEtree => {
            let tpt = read_ref(r, n)?;
            let where_clauses = read_refs_until(r, end, n)?;
            Tree::ExistentialTypeTree { tpt, where_clauses }
        }
        _ => return r.err(format!("unknown tree tag {tt}")),
    };
    Ok(Entry::Tree { tpe, tree })
}

