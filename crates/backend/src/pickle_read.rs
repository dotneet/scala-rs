/// A pickle that could not be read, pinpointed to the offending entry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ReadError {
    /// Index of the entry being parsed (`usize::MAX` for the header).
    pub entry: usize,
    /// Tag byte of the entry being parsed (0 for the header).
    pub tag: u8,
    /// Byte offset within the pickle where the failure was detected.
    pub offset: usize,
    pub message: String,
}

impl fmt::Display for ReadError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.entry == usize::MAX {
            write!(f, "pickle header at {}: {}", self.offset, self.message)
        } else {
            write!(
                f,
                "entry #{} (tag {}) at byte {}: {}",
                self.entry, self.tag, self.offset, self.message
            )
        }
    }
}

type Result<T> = std::result::Result<T, ReadError>;

