//! Full reader for the nsc 2.13 `ScalaSignature` pickle format.
//!
//! `pickle.rs` is the *writer* (a subset of nsc `PickleFormat`) plus a small
//! ad-hoc unpickler that only recovers what scala-rs itself emits. This module
//! is the complement: a **complete** reader for the format as produced by
//! scalac 2.13, able to parse every entry of every `.class` in
//! `scala-library-2.13.16.jar`.
//!
//! Layout (nsc `PickleBuffer` / `UnPickler`):
//!
//! ```text
//! pickle  = majorVersion_Nat minorVersion_Nat nentries_Nat { Entry }
//! Entry   = tag_Nat len_Nat [len bytes]
//! ```
//!
//! All references between entries are entry indices written as `Nat`
//! (big-endian base-128). Every entry body is parsed to the byte, and the
//! reader *fails* (rather than silently skipping) when a tag is unknown, when
//! a body is malformed, or when a body is not consumed exactly — that
//! exactness check is what makes this reader a useful regression test against
//! the real standard library.

