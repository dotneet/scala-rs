impl Entry {
    /// The `SymInfo` of any non-external symbol entry.
    pub fn sym_info(&self) -> Option<&SymInfo> {
        match self {
            Entry::TypeSym(i)
            | Entry::AliasSym(i)
            | Entry::ClassSym { info: i, .. }
            | Entry::ModuleSym { info: i, .. }
            | Entry::ValSym { info: i, .. } => Some(i),
            _ => None,
        }
    }
}

/// A fully parsed pickle.
#[derive(Clone, Debug)]
pub struct Pickle {
    pub major: u32,
    pub minor: u32,
    pub entries: Vec<Entry>,
    /// Tag byte of each entry, in table order.
    pub entry_tags: Vec<u8>,
}

impl Pickle {
    pub fn entry(&self, i: Idx) -> Option<&Entry> {
        self.entries.get(i as usize)
    }

    /// Text of a `TERMname` / `TYPEname` entry.
    pub fn name(&self, i: Idx) -> Option<&str> {
        match self.entries.get(i as usize)? {
            Entry::TermName(s) | Entry::TypeName(s) => Some(s.as_str()),
            _ => None,
        }
    }

    /// The name entry of a symbol (internal or external).
    pub fn sym_name(&self, i: Idx) -> Option<&str> {
        match self.entries.get(i as usize)? {
            Entry::ExtRef { name, .. } | Entry::ExtModClassRef { name, .. } => self.name(*name),
            e => self.name(e.sym_info()?.name),
        }
    }

    /// The owner entry of a symbol, if it has one.
    pub fn sym_owner(&self, i: Idx) -> Option<Idx> {
        match self.entries.get(i as usize)? {
            Entry::ExtRef { owner, .. } | Entry::ExtModClassRef { owner, .. } => *owner,
            e => Some(e.sym_info()?.owner),
        }
    }

    /// Dotted name of a symbol, walking owners up to the root.
    pub fn sym_full_name(&self, i: Idx) -> Option<String> {
        let mut parts: Vec<&str> = Vec::new();
        let mut cur = Some(i);
        let mut guard = 0;
        while let Some(c) = cur {
            guard += 1;
            if guard > 64 {
                return None;
            }
            let n = self.sym_name(c)?;
            if n == "<root>" || n == "<empty>" {
                break;
            }
            parts.push(n);
            cur = self.sym_owner(c);
        }
        parts.reverse();
        Some(parts.join("."))
    }
}

